#!/usr/bin/env node
/**
 * Prasanth's Performance Portal — Setup Script
 * Run once on each machine: node scripts/setup.js
 *
 * What it does:
 *  1. Checks Node.js version (≥18 required)
 *  2. Asks for config (ports, admin password)
 *  3. Writes backend/.env with secure random JWT secret
 *  4. Generates a self-signed TLS cert for THIS machine's hostname
 *  5. Installs backend + frontend dependencies
 *  6. Builds the React frontend
 *
 * PostgreSQL is EMBEDDED — no installation required.
 * No openssl needed — cert is generated with Node's built-in crypto.
 */

const { spawnSync } = require('child_process');
const fs       = require('fs');
const path     = require('path');
const readline = require('readline');
const crypto   = require('crypto');
const os       = require('os');

const ROOT     = path.join(__dirname, '..');
const BACKEND  = path.join(ROOT, 'backend');
const FRONTEND = path.join(ROOT, 'frontend');

// Re-use the cert generator (same file, no duplication)
const { generateCert } = require('./generate-cert');

function run(cmd, cwd = ROOT) {
  console.log(`  > ${cmd}`);
  const result = spawnSync(cmd, { shell: true, cwd, stdio: 'inherit' });
  if (result.status !== 0) {
    console.error(`\n[ERROR] Command failed: ${cmd}`);
    process.exit(1);
  }
}

function ask(rl, question) {
  return new Promise(resolve => rl.question(question, resolve));
}

// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  const hostname = os.hostname();

  console.log('\n========================================');
  console.log("  Prasanth's Performance Portal — Setup");
  console.log('  PostgreSQL is bundled. Nothing extra');
  console.log('  to install!');
  console.log(`  Machine hostname: ${hostname}`);
  console.log('========================================\n');

  // 1. Check Node.js
  const major = parseInt(process.version.slice(1).split('.')[0]);
  if (major < 18) {
    console.error(`[FAIL] Node.js ${process.version} is too old. Need v18+.`);
    console.error('       Download from: https://nodejs.org');
    process.exit(1);
  }
  console.log(`✅ Node.js ${process.version}`);
  console.log('✅ PostgreSQL: embedded (no install needed)\n');

  // 2. Ask for config
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const adminPass  = (await ask(rl, 'Admin password for the app [Admin@1234]: ')).trim() || 'Admin@1234';
  const httpPort   = (await ask(rl, 'Internal HTTP port  [3001]: ')).trim() || '3001';
  const httpsPort  = (await ask(rl, 'Internal HTTPS port [3443]: ')).trim() || '3443';
  const useProxy   = (await ask(rl, 'Set up port forwarding 443→' + httpsPort + ' so URL has no port number? [Y/n]: ')).trim().toLowerCase();
  rl.close();

  const wantProxy  = useProxy === '' || useProxy === 'y' || useProxy === 'yes';
  const pubHttps   = wantProxy ? 443 : parseInt(httpsPort);
  const pubHttp    = wantProxy ? 80  : parseInt(httpPort);

  // 3. Write .env
  const jwtSecret = crypto.randomBytes(48).toString('hex');
  const env = `# Prasanth's Performance Portal configuration
# Generated by setup.js — do not commit this file

HTTP_PORT=${httpPort}
HTTPS_PORT=${httpsPort}

# Public-facing ports (browser sees these).
# If using netsh port proxy (443→${httpsPort}), PUBLIC_HTTPS_PORT=443 omits port from URLs.
PUBLIC_HTTP_PORT=${pubHttp}
PUBLIC_HTTPS_PORT=${pubHttps}

# Embedded PostgreSQL settings (managed automatically)
DB_HOST=localhost
DB_PORT=5433
DB_USER=postgres
DB_PASSWORD=postgres
DB_NAME=jtl_super_app
EMBEDDED_PG_PORT=5433

# Auth
JWT_SECRET=${jwtSecret}
JWT_EXPIRES_IN=8h

# Admin account (used only on first startup)
ADMIN_PASSWORD=${adminPass}

# Upload settings
NODE_ENV=production
UPLOAD_DIR=uploads
MAX_FILE_SIZE_MB=500
`;
  fs.writeFileSync(path.join(BACKEND, '.env'), env);
  console.log('\n✅ .env written');

  // 4. Install dependencies (before the cert step: it needs node-forge
  //    on machines that have no OpenSSL / Git installed)
  console.log('\n--- Installing backend dependencies ---');
  run('npm install --omit=dev', BACKEND);

  console.log('\n--- Installing frontend dependencies ---');
  run('npm install', FRONTEND);

  // 5. Build frontend
  console.log('\n--- Building frontend ---');
  run('npm run build', FRONTEND);

  // 6. Generate TLS certificate for THIS machine's hostname.
  //    Non-fatal: without a cert the app still runs, on plain HTTP.
  console.log(`\n--- Generating TLS certificate for hostname: ${hostname} ---`);
  let httpsReady = false;
  try {
    const { KEY_FILE, CRT_FILE, method } = generateCert(hostname);
    console.log(`✅ Certificate: ${CRT_FILE}`);
    console.log(`✅ Private key: ${KEY_FILE}`);
    console.log(`   Method     : ${method}`);
    httpsReady = true;
  } catch (err) {
    console.warn(`⚠  Could not create a TLS certificate: ${err.message}`);
    console.warn('   The app will run on plain HTTP until you run: node scripts/generate-cert.js');
  }

  // 7. Done
  const localUrl   = pubHttps === 443 ? `https://localhost`        : `https://localhost:${httpsPort}`;
  const networkUrl = pubHttps === 443 ? `https://${hostname}`      : `https://${hostname}:${httpsPort}`;
  const httpUrl    = pubHttp  === 80  ? `http://${hostname}`       : `http://${hostname}:${httpPort}`;

  console.log('\n========================================');
  console.log('  ✅  Setup complete!');
  console.log('========================================');
  console.log('\n  To start:   START.bat   (or: node backend/src/app.js)');

  if (httpsReady) {
    console.log(`\n  Local:      ${localUrl}`);
    console.log(`  Network:    ${networkUrl}`);
    console.log(`  (HTTP ${httpUrl} redirects to HTTPS)`);
  } else {
    console.log(`\n  Local:      http://localhost:${httpPort}`);
    console.log(`  Network:    http://${hostname}:${httpPort}`);
  }

  if (wantProxy && httpsReady) {
    console.log('\n  ⚡ Port forwarding needed (run ONCE as Administrator):');
    console.log('  ┌─────────────────────────────────────────────────────────┐');
    console.log(`  │  netsh interface portproxy add v4tov4 \\`);
    console.log(`  │    listenport=443 listenaddress=0.0.0.0 \\`);
    console.log(`  │    connectport=${httpsPort} connectaddress=127.0.0.1`);
    console.log(`  │  netsh interface portproxy add v4tov4 \\`);
    console.log(`  │    listenport=80 listenaddress=0.0.0.0 \\`);
    console.log(`  │    connectport=${httpPort} connectaddress=127.0.0.1`);
    console.log('  └─────────────────────────────────────────────────────────┘');
    console.log('  Or run:  .\\scripts\\setup-ports.ps1  (as Administrator)');
  }

  if (httpsReady) {
    console.log('\n  ⚠  On first browser visit: click Advanced → Proceed');
    console.log(`     (self-signed cert for ${hostname} — expected)`);
  }
  console.log(`\n  Login:  admin / ${adminPass}`);
  console.log('  ⚠  Change your password after first login!');
  console.log('========================================\n');
}

main().catch(err => { console.error(err); process.exit(1); });
